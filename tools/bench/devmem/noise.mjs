function mulberry32(seed) {
  let state = seed
  return () => {
    state = (state + 0x6d2b79f5) | 0
    let t = Math.imul(state ^ (state >>> 15), 1 | state)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const DAY_MS = 86_400_000

/** @returns {Array<{id:string,date:string,cwd:string,messages:Array<{role:string,text:string}>}>} */
export function generateNoise(count, { seed = 20261, from = '2026-03-01', to = '2026-10-28' } = {}) {
  const rand = mulberry32(seed)
  const pick = (items) => items[Math.floor(rand() * items.length)]
  const start = Date.parse(`${from}T00:00:00Z`)
  const days = Math.round((Date.parse(`${to}T00:00:00Z`) - start) / DAY_MS)
  const sessions = []
  for (let index = 0; index < count; index += 1) {
    const project = pick(PROJECTS)
    const fill = (text) =>
      text.replaceAll('{p}', project).replaceAll('{m}', pick(MODULES)).replaceAll('{w}', pick(WORDS))
    const messages = []
    const say = (role, text) => messages.push({ role, text: fill(text) })
    // 一个会话聊一到两个话题，长度才不至于全都一样。
    for (let turn = 0, turns = 1 + Math.floor(rand() * 2); turn < turns; turn += 1) {
      const [asks, answers, followUps] = pick(TOPICS)
      say('user', pick(asks))
      say('assistant', pick(answers))
      if (rand() < 0.7) {
        const [ask, answer] = pick(followUps)
        say('user', ask)
        say('assistant', answer)
      }
    }
    const day = Math.floor(((index + rand()) / count) * days)
    sessions.push({
      id: `n${String(index + 1).padStart(3, '0')}`,
      date: new Date(start + day * DAY_MS).toISOString().slice(0, 10),
      cwd: `D:/work/${project}`,
      messages,
    })
  }
  return sessions
}
